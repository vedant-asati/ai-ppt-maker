"""
font_downloader.py — Download Google Fonts for offline rendering.

Downloads the 5 fonts used by base.html into assets/fonts/.
Generates a fonts.css @font-face bundle so Playwright can render
without any network requests (faster, reproducible, works offline).

Fonts downloaded:
  - Inter (Regular, Medium, SemiBold, Bold, ExtraBold)
  - Merriweather (Light, Regular, Bold, Italic)
  - Space Grotesk (Regular, Medium, SemiBold, Bold)
  - DM Serif Display (Regular, Italic)
  - Playfair Display (Bold, ExtraBold, Italic Bold)
  - Noto Serif Devanagari (variable weight)
"""

import os
import urllib.request
import urllib.error
import urllib.parse
from typing import Optional

# Google Fonts CSS API URLs (subset: latin)
_GOOGLE_FONTS_API = "https://fonts.googleapis.com/css2?{}&display=swap"
_FAMILIES = [
    "family=Inter:wght@300;400;500;600;700;800",
    "family=Merriweather:ital,wght@0,300;0,400;0,700;1,300;1,400",
    "family=Space+Grotesk:wght@400;500;600;700",
    "family=DM+Serif+Display:ital@0;1",
    "family=Playfair+Display:ital,wght@0,700;0,800;1,700",
    "family=Noto+Serif+Devanagari:wght@400;700",
]

_USER_AGENT = (
    "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 "
    "(KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36"
)


def download_fonts(fonts_dir: str = 'assets/fonts', verbose: bool = True) -> bool:
    """
    Download all required fonts into fonts_dir.
    Returns True if successful, False if any font fails to download.
    """
    os.makedirs(fonts_dir, exist_ok=True)

    # Collect all font URLs from the Google Fonts CSS API
    all_font_urls = []
    css_chunks = []

    for family_param in _FAMILIES:
        url = _GOOGLE_FONTS_API.format(family_param)
        if verbose:
            print(f"  Fetching font metadata: {family_param.split('=')[1].split(':')[0]}")

        try:
            req = urllib.request.Request(url, headers={'User-Agent': _USER_AGENT})
            with urllib.request.urlopen(req, timeout=10) as resp:
                css_text = resp.read().decode('utf-8')
            css_chunks.append(css_text)

            # Parse woff2 URLs from the CSS
            import re
            urls = re.findall(r"url\((https://fonts\.gstatic\.com/[^\)]+\.woff2)\)", css_text)
            all_font_urls.extend(urls)

        except Exception as e:
            if verbose:
                print(f"  [Warning] Could not fetch font CSS for {family_param}: {e}")
            continue

    if not all_font_urls:
        print("  [Error] No font URLs found. Check your internet connection.")
        return False

    # Deduplicate
    all_font_urls = list(dict.fromkeys(all_font_urls))

    if verbose:
        print(f"  Downloading {len(all_font_urls)} font files...")

    # Download each woff2
    failed = 0
    url_to_local: dict = {}
    for i, url in enumerate(all_font_urls):
        fname = _url_to_filename(url)
        local_path = os.path.join(fonts_dir, fname)
        url_to_local[url] = fname

        if os.path.exists(local_path):
            if verbose:
                print(f"  [Cache] {fname}")
            continue

        try:
            req = urllib.request.Request(url, headers={'User-Agent': _USER_AGENT})
            with urllib.request.urlopen(req, timeout=15) as resp:
                data = resp.read()
            with open(local_path, 'wb') as f:
                f.write(data)
            if verbose:
                size_kb = len(data) // 1024
                print(f"  [{i+1:02d}/{len(all_font_urls):02d}] {fname} ({size_kb} KB)")
        except Exception as e:
            if verbose:
                print(f"  [Error] Failed to download {fname}: {e}")
            failed += 1

    # Patch CSS to use local paths and write fonts.css
    fonts_css_path = os.path.join(fonts_dir, 'fonts.css')
    combined_css = '\n'.join(css_chunks)

    # Replace remote URLs with local filenames
    import re
    def replace_url(m):
        orig_url = m.group(1)
        fname = url_to_local.get(orig_url)
        if fname:
            return f"url('{fname}')"
        return m.group(0)

    local_css = re.sub(
        r"url\((https://fonts\.gstatic\.com/[^\)]+\.woff2)\)",
        replace_url,
        combined_css
    )
    # Remove remote @import statements (if any)
    local_css = re.sub(r"@import url\([^)]+\);", "", local_css)

    with open(fonts_css_path, 'w', encoding='utf-8') as f:
        f.write(f"/* Auto-generated by font_downloader.py */\n")
        f.write(f"/* Place this file alongside the .woff2 files in assets/fonts/ */\n\n")
        f.write(local_css)

    if verbose:
        if failed == 0:
            print(f"\n  ✓ All fonts saved to {fonts_dir}/")
            print(f"  ✓ fonts.css written — Playwright will use local fonts from now on.")
        else:
            print(f"\n  ⚠ {failed}/{len(all_font_urls)} fonts failed to download.")
            print(f"  Partial local font bundle saved to {fonts_dir}/")

    return failed == 0


def _url_to_filename(url: str) -> str:
    """Convert a Google Fonts CDN URL to a safe local filename."""
    # e.g. https://fonts.gstatic.com/s/inter/v13/UcCO3FwrK3iLTeHuS_fvQtMwCp50KnMw2boKoduKmMEVuLyfAZ9hiJ.woff2
    # → inter_UcCO3Fw...woff2
    parts = url.split('/')
    family_part = parts[5] if len(parts) > 6 else 'font'
    hash_part   = parts[-1]  # e.g. UcCO...woff2
    return f"{family_part}_{hash_part}"
